| Google Generative Language API(Gemini) | AI_SCHEDULE_PARSING 현행 버전에 선택 동의한 이용자의 시간 표현이 포함된 일정 날짜와 내용 텍스트 | 일정 텍스트에서 시작·종료 시간과 시간 표현을 제외한 제목 추출 |

일정 시간 자동 인식은 이용자가 AI_SCHEDULE_PARSING 현행 버전에 명시적으로 선택 동의한 경우에만 사용합니다. 이용자는 설정에서 언제든 철회할 수 있고, 서버는 일정 저장 시와 큐의 외부 API 호출 직전에 현재 동의와 정책 버전을 다시 확인합니다. 동의하지 않거나 철회한 경우에는 Google로 전송하지 않으며 날짜와 시간을 직접 입력할 수 있습니다.

운영자는 Cloud Billing이 활성화된 paid service에 Google의 Data Processing Addendum(DPA)이 적용되는 것을 확인한 Cloud Project의 API key만 구성해야 합니다. 이 조건을 확인하기 전에는 production에서 AI 자동 인식을 사용하지 않으며, unpaid service에는 일정 날짜나 내용 텍스트를 전송하지 않습니다.

Kakao·Naver access token은 위 식별자 조회에만 일시 사용하고 Dutypark 데이터베이스에 저장하지 않습니다. 외부 서비스의 실제 처리·보관은 각 서비스의 약관과 정책 및 운영 계약의 적용을 받을 수 있습니다. 해외 이전 국가, 외부 사업자의 보관기간 등 법적 고지 필드는 확인되지 않은 값을 임의로 기재하지 않으며, 운영 계약 확인과 별도 법률 검토 후 필요한 내용을 추가 고지합니다.


## 제8조 이용자의 권리와 안전성 확보 조치

1. 이용자는 서비스 설정과 제공되는 문의 채널을 통해 개인정보 열람, 정정, 삭제, 처리 정지 및 동의 철회를 요청할 수 있습니다. 공동 데이터나 다른 이용자의 권리와 관련된 요청은 해당 관계와 권한을 확인해 처리합니다.
2. 서비스는 비밀번호를 bcrypt 해시로 저장하고 원문을 보관하지 않으며, HTTPS 통신, HttpOnly·Secure·SameSite 쿠키, 접근 권한 및 첨부 context 권한 검사를 적용합니다.
3. 로그인 시도 횟수 제한, 세션 만료·삭제, OAuth state·PKCE·일회용 코드 검증을 통해 부정 접근과 재사용을 줄입니다.


