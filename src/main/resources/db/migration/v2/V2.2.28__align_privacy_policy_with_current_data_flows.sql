## 제4조 쿠키 및 기기 저장소

1. 서비스는 로그인 상태를 유지하기 위해 access_token과 refresh_token이라는 HttpOnly 쿠키를 사용합니다. 이 쿠키는 광고 또는 이용자 추적용 쿠키가 아닙니다.
2. access_token 쿠키의 path는 /이고 기본 유효기간은 30분입니다. refresh_token 쿠키의 path는 /api/auth이고 기본 유효기간은 7일이며 갱신될 수 있습니다.
3. 두 쿠키에는 SameSite=Lax가 적용되고 운영 환경에서는 Secure 속성을 사용합니다. HttpOnly 속성으로 웹 스크립트가 토큰 값을 읽을 수 없도록 합니다.
4. 웹은 localStorage에 인증 토큰을 저장하지 않습니다. 다만 dp-login-member 회원 기본 캐시, 선택적으로 기억한 이메일, 테마·언어·필터·선택 D-Day·가이드 표시 상태·관리자 대리 로그인 만료 등 편의 정보를 저장할 수 있습니다.
5. iOS 앱은 URLSession의 cookie storage를 통해 같은 HttpOnly 쿠키 세션을 사용하며 UserDefaults에 인증 토큰을 저장하지 않습니다. 선택적으로 기억한 이메일, 언어·화면 선택 상태, dutypark.apns.device-token 및 push enabled preference는 UserDefaults에 저장될 수 있습니다.
6. 로그아웃하면 서버 갱신 세션과 인증 쿠키를 정리하고 iOS도 로컬 인증 쿠키를 정리합니다. 편의 정보와 푸시 설정은 항목에 따라 로그아웃, 서비스 설정, 브라우저 데이터 삭제 또는 앱 삭제로 정리할 수 있습니다.


## 제5조 푸시 알림 처리

1. 푸시 알림은 이용자가 브라우저 또는 iOS에서 권한을 허용하고 등록한 경우에만 사용하는 opt-in 기능입니다.
2. Web Push 구독의 endpoint·p256dh·auth와 APNs device token·sandbox 여부는 각각 현재 refresh session에 귀속됩니다.
3. 알림 payload에는 알림 유형, 알림 ID, 딥링크 URL, 안읽음 수가 포함될 수 있습니다. 화면 표시를 위해 발신자 이름과 일정 또는 Todo 제목이 포함될 수 있습니다.
4. iOS 알림은 Apple Push Notification service(APNs)로, Web Push는 이용 중인 브라우저의 push service로 전송됩니다.
5. 이용자가 알림을 해제하거나 로그아웃하는 경우, 갱신 세션을 삭제하는 경우, 갱신 세션이 만료되어 정리되는 경우 관련 등록도 제거됩니다. Web Push provider의 404·410 응답, APNs의 410 응답 등 구독 만료가 확인된 경우에도 서버 등록을 제거합니다.


## 제6조 첨부파일 처리 및 공유

1. 업로드 시 원본 파일과 원본 파일명, MIME type, 크기, 서버 저장 파일명·경로, thumbnail 및 metadata, context와 uploader를 처리합니다.
2. 미완료 upload session은 24시간 유효하고 매일 02시 정리합니다. 완료된 파일은 임시 위치에서 해당 SCHEDULE·PROFILE·TEAM·TODO 저장 위치로 이동합니다.
3. 일정 공개 범위, Todo 참여 관계, 프로필 공개 읽기 등 해당 기능의 권한을 가진 이용자에게 첨부파일이 표시·다운로드·공유될 수 있습니다.
4. 완료 파일은 관련 컨텍스트가 유지되는 동안 또는 이용자가 개별 삭제할 때까지 보유합니다. 계정 삭제 시 공동 TEAM 데이터나 다른 이용자와 관련된 컨텍스트의 처리 결과에 따라 일부 파일의 처리 시점과 방식이 달라질 수 있습니다.


## 제7조 소셜 OAuth 및 외부 서비스 이용

서비스는 원칙적으로 이용자의 개인정보를 목적 범위 밖에서 제3자에게 제공하지 않습니다. 다음 외부 서비스는 이용자가 요청한 인증, 알림 또는 일정 시간 추출을 수행하기 위해 사용합니다.

| 외부 서비스 | 실제 전송·수신 정보 | 이용 목적 |
